def _paper_operator(name):
    """The coefficient tensor, Dirac structure, number of indices and irrep of an explicit operator of the paper."""
    op = REFERENCE["explicit_operators"][name]
    n = len(op["terms"][0][0])
    c = np.zeros((4,) * n)
    for indices, value in op["terms"]:
        c[tuple(int(i) - 1 for i in indices)] += value
    return c, op["X"], n, _label(op["irrep"])


@pytest.mark.parametrize("name", [name for name in REFERENCE["explicit_operators"] if not name.startswith("_")])
def test_paper_operators_are_in_the_database(name):
    """The operators of eqs. (7.20), (8.12), (9.17) are combinations of the database operators of their irrep, and of no other."""
    c, X, n, irrep = _paper_operator(name)
    ops = [op for op in get_OperatorList(X=X, group="honeycomb") if op.n == n]
    in_irrep = np.array([op.cgmat.ravel() for op in ops if op.irrep == irrep]).T
    others = np.array([op.cgmat.ravel() for op in ops if op.irrep != irrep]).T
    coefficients = np.linalg.lstsq(in_irrep, c.ravel(), rcond=None)[0]
    assert np.allclose(in_irrep @ coefficients, c.ravel(), atol=1e-12)
    # together the operators span all tensors, so no operator of another irrep is needed (or contributes)
    everything = np.linalg.lstsq(np.hstack([in_irrep, others]), c.ravel(), rcond=None)[0]
    assert np.allclose(everything[in_irrep.shape[1] :], 0, atol=1e-12)


