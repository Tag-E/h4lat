    assert (loaded.group, loaded.irrep, loaded.id) == ("honeycomb", op.irrep, op.id)
    assert np.array_equal(loaded.cgmat, op.cgmat)
    # a folder of honeycomb operators is read with its group, and refused as H(4)
    assert OperatorList_from_database(str(tmp_path / "hc"))[0].group == "honeycomb"
    assert OperatorList_from_database(str(tmp_path / "hc"), group="honeycomb")[0].irrep == op.irrep
