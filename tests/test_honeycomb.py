def test_elements_are_h4_and_its_triality_cosets(elements):
    """Elements 0-383 are h4lat's H(4) in its order; element 384·j + i is H(4)[i]·Aʲ, with A³ = 1."""
    h4 = cg_calc((4, 1), (4, 1), verbose=False).group_mat[H4.irrep_index[(4, 1)]]
    A = np.array(REFERENCE["triality_A_eq_3_2_times_2"], dtype=float) / 2
    assert np.array_equal(A, TRIALITY)
    assert np.allclose(np.linalg.matrix_power(A, 3), np.eye(4))
    for j in range(3):
        assert np.allclose(elements[384 * j : 384 * (j + 1)], h4 @ np.linalg.matrix_power(A, j))
    assert len({_key(g) for g in elements}) == 1152


def test_the_paper_generators_generate_the_group(elements):
    """g₁ (eq. 3.1) and g₂ (eq. 3.3) are elements, g₁² = g₂⁶ = 1, and the words in them give all 1152 elements."""
    generators = REFERENCE["generators_eq_3_1_3_3"]
    g1 = np.array(generators["g1"], dtype=float)
    g2 = np.array(generators["g2_WF4_times_2"], dtype=float) / 2
    assert np.array_equal(g1, GENERATORS[0]) and np.array_equal(g2, GENERATORS[1])
    assert np.allclose(g1 @ g1, np.eye(4)) and np.allclose(np.linalg.matrix_power(g2, 6), np.eye(4))
    keys = {_key(g) for g in elements}
    # breadth-first search from the identity: every element reached is a product of generators
    reached, frontier = {_key(np.eye(4))}, [np.eye(4)]
    while frontier:
        new = []
        for g in frontier:
            for s in (g1, g2):
                h = s @ g
                if _key(h) not in reached:
                    reached.add(_key(h))
                    new.append(h)
        frontier = new
    assert reached == keys


def test_the_group_preserves_the_lattice(elements):
    """Every element maps the 24 short roots ±e_μ, (±½)⁴ and the 24 long roots ±e_μ ± e_ν onto themselves (F₄)."""
    short = [s * np.eye(4)[i] for i in range(4) for s in (1, -1)] + [
        np.array(v) / 2 for v in it.product((1, -1), repeat=4)
    ]
    long_ = [
        s * np.eye(4)[i] + t * np.eye(4)[j] for i, j in it.combinations(range(4), 2) for s in (1, -1) for t in (1, -1)
    ]
    for roots in (short, long_):
        R = np.array(roots)
        root_keys = {tuple(np.rint(2 * r).astype(int)) for r in R}
        images = np.einsum("gab,rb->gra", elements, R)
        assert all({tuple(np.rint(2 * v).astype(int)) for v in image} == root_keys for image in images)


