def test_table_1_continuum_representations(elements, characters):
    """Table 1: the O(4) representations (symmetric traceless tensors Hₙ, Mₙ, W, …) in terms of W(F₄) irreps."""
    eigenvalues = np.linalg.eigvals(elements)
    tr = np.trace(elements, axis1=1, axis2=2)
    det = np.rint(np.linalg.det(elements))

    def h(n, e):
        """Character of the symmetric tensors of rank n: the complete homogeneous polynomial of the eigenvalues."""
        return 0 if n < 0 else sum(np.prod(c) for c in it.combinations_with_replacement(e, n)).real

    def H(n):
        """Character of Hₙ, the symmetric traceless tensors of rank n: Symⁿ − Symⁿ⁻²."""
        return np.array([h(n, e) - h(n - 2, e) for e in eigenvalues])

    def M(n):
        """Character of M_{n+1}, the tensors of mixed symmetry [n, 1]: R ⊗ Hₙ − Hₙ₊₁ − Hₙ₋₁."""
        return tr * H(n) - H(n + 1) - H(n - 1)

    pairs = list(it.combinations(range(4), 2))
    L2 = np.array(
        [[[g[a, c] * g[b, e] - g[a, e] * g[b, c] for (c, e) in pairs] for (a, b) in pairs] for g in elements]
    )
    trL, trL2 = np.trace(L2, axis1=1, axis2=2), np.trace(L2 @ L2, axis1=1, axis2=2)
    representations = {
        "1": np.ones(len(elements)), "det": det, "R": tr, "det R": det * tr, "A": characters[(6, 1)],
        "H2": H(2), "det H2": det * H(2), "W": (trL**2 + trL2) / 2 - 1 - det - H(2), "M3": M(2),
        "H3": H(3), "det H3": det * H(3), "H4": H(4), "det H4": det * H(4), "M4": M(3),
    }  # fmt: skip
    for name, chi in representations.items():
        assert _decompose(chi, characters, 1152) == REFERENCE["table1_WF4"][name], name


def test_rest_frame_irreps(elements, characters):
    """Eqs. (6.4) and (6.11): the irreps with a non-zero matrix element in a nucleon at rest, unpolarised and polarised."""
    short = [s * np.eye(4)[i] for i in range(4) for s in (1, -1)] + [
        np.array(v) / 2 for v in it.product((1, -1), repeat=4)
    ]
    # functions on the orbit of p = (0, 0, 0, E): the 24 short roots; the character counts the fixed ones
    F = np.array([sum(np.allclose(g @ r, r) for r in short) for g in elements], dtype=float)
    det = np.rint(np.linalg.det(elements))
    tr = np.trace(elements, axis1=1, axis2=2)
    assert _decompose(F, characters, 1152) == REFERENCE["eq_6_4_rest_frame_unpolarized"]
    assert _decompose(det * (tr * F - F), characters, 1152) == REFERENCE["eq_6_11_rest_frame_polarized"]


def test_four_fermion_operators(characters, elements):
    """Eq. (10.1) (C = ±1 summed): the 16 Dirac structures tensored with themselves."""
    det = np.rint(np.linalg.det(elements))
    tr = np.trace(elements, axis1=1, axis2=2)
    dirac = 1 + det + tr + det * tr + characters[(6, 1)]
    assert _decompose(dirac**2, characters, 1152) == REFERENCE["eq_10_1_four_fermion_totals"]


