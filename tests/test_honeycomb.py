def _label(text):
    """A label of the reference data, 'k,l', as an irrep (k, l)."""
    return tuple(int(x) for x in text.split(","))


def _text(label):
    """An irrep (k, l) as a label of the reference data, 'k,l'."""
    return f"{label[0]},{label[1]}"


def _key(mat):
    """Exact, hashable key of a 4×4 matrix with entries in ½ℤ (all elements of W(F₄))."""
    return tuple(np.rint(2 * np.asarray(mat)).astype(int).ravel())


