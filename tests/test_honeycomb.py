def _decompose(character, characters, order):
    """Multiplicities {'k,l': m} (non-zero only) of a (virtual) character, by the orthogonality of characters."""
    result = {}
    for label, chi in characters.items():
        m = character @ chi / order
        assert abs(m - round(m)) < 1e-9, f"non-integer multiplicity {m} of {label}"
        if round(m):
            result[_text(label)] = int(round(m))
    return result


