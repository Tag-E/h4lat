def test_operator_file_names_record_the_group(tmp_path):
    """Honeycomb operators are saved with the suffix _honeycomb and read back as such; H(4) names are unchanged."""
    op = get_OperatorList(keys="V1", group="honeycomb")[3]
    op.save(str(tmp_path / "hc"))
    (path,) = (tmp_path / "hc").iterdir()
    assert path.name == f"operator_{op.id}_2_V_{op.irrep[0]}_{op.irrep[1]}_{op.block}_{op.index_block}_honeycomb.npy"
